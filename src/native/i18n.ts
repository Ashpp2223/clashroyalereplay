export type Message = { key: TextKey; values?: Record<string, string | number | { key: TextKey }> };
export function message(key: TextKey, values?: Message['values']): Message { return { key, values }; }
export function storedLanguage(): Language {
  try { return localStorage.getItem(LANGUAGE_KEY) === 'en-US' ? 'en-US' : 'zh-CN'; } catch { return 'zh-CN'; }
}
export function translate(language: Language, key: TextKey, values?: Message['values']): string {
  return (language === 'en-US' ? en[key] : zh[key]).replace(/\{(\w+)\}/g, (_, name: string) => typeof values?.[name] === "object" ? translate(language,(values![name] as {key:TextKey}).key) : String(values?.[name] ?? `{${name}}`));
}
export function text(key: TextKey): string { return translate(storedLanguage(), key); }
const Context = createContext<{ language: Language; toggle: () => void }>({ language: 'zh-CN', toggle: () => {} });
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState(storedLanguage);
  useEffect(() => { document.documentElement.lang = language; document.title = translate(language,"brand"); }, [language]);
  const toggle = () => setLanguage(current => {
    const next = current === 'zh-CN' ? 'en-US' : 'zh-CN';
    try { localStorage.setItem(LANGUAGE_KEY, next); } catch { /* UI still switches in memory. */ }
    return next;
  });
  return createElement(Context.Provider, { value: { language, toggle } }, children);
}
export function useI18n() {
  const { language, toggle } = useContext(Context);
  return { language, toggle, t: (key: TextKey, values?: Message['values']) => translate(language, key, values),
    renderMessage: (value: Message | string) => typeof value === 'string' ? value : translate(language, value.key, value.values) };
}

export { NativeUiError } from "../domain/errors.ts";
export function errorText(error: unknown, language: Language): string {
  return error instanceof NativeUiError ? translate(language,error.code) : String(error);
}

const STAGE_KEYS = {
  idle: 'runtimeNotStarted', checking: 'runtimeCheck', android: 'runtimeAndroid', verifying: 'runtimeVerify',
  probe: 'runtimeProbe', capabilities: 'runtimeCapabilities', ready: 'runtimeReady', emulator: 'runtimeEmulator',
  resources: 'runtimeResources', installing: 'runtimeInstall', failed: 'runtimeFailed',
  download: 'setupDownload', image: 'setupImage', setupVerify: 'setupVerify', installed: 'setupInstalled',
  importing: 'setupImport', boot: 'setupBoot', battle: 'setupBattle', complete: 'setupComplete',
} satisfies Record<string,TextKey>;
export function stageText(language:Language,code?:string,fallback=''):string {
  return code && code in STAGE_KEYS ? translate(language,STAGE_KEYS[code as keyof typeof STAGE_KEYS]) : fallback;
}
